'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const source = fs.readFileSync('apps-script/Code.gs', 'utf8');
function functionSource(name) {
  const start = source.indexOf('function ' + name + '(');
  assert.notEqual(start, -1, 'Required function exists: ' + name);
  const next = source.indexOf('\nfunction ', start + 10);
  return source.slice(start, next < 0 ? source.length : next);
}
const sanitizer = functionSource('sanitizeAuditValue_');
assert.match(sanitizer, /password\|passhash\|salt\|token\|otp\|secret/);
assert.match(sanitizer, /fileid\|fileurl/);
assert.match(sanitizer, /email\|phone\|mobile\|address\|nik\|nisn/);
assert.match(sanitizer, /JSON\.parse\(raw\)/);
assert.match(sanitizer, /JSON\.stringify\(cleanNode_\(JSON\.parse\(raw\)\)\)|JSON\.stringify\(cleanNode_\(JSON\.parse/);
const textRedactor = functionSource('redactAuditText_');
assert.match(textRedactor, /REDACTED_EMAIL/);
assert.match(textRedactor, /REDACTED_PHONE/);
assert.match(textRedactor, /REDACTED_TOKEN/);
const writer = functionSource('writeAudit_');
assert.match(writer, /sanitizeAuditValue_\(oldValue\)/);
assert.match(writer, /sanitizeAuditValue_\(newValue\)/);
assert.match(writer, /sanitizeAuditValue_\(description\)/);
assert.match(writer, /AUDIT_LOG_WRITE_FAILED/);
assert.doesNotMatch(writer, /console\.error\([^)]*\+\s*e/);
const reader = functionSource('getAuditLogPageData');
assert.match(reader, /requireRole_\(sessionToken,\s*PSB_AUDIT_ACCESS_ROLES\)/);
assert.match(reader, /oldValue:sanitizeAuditValue_\(r\[idx\.oldValue\]\)/);
assert.match(reader, /newValue:sanitizeAuditValue_\(r\[idx\.newValue\]\)/);
assert.match(reader, /description:sanitizeAuditValue_\(r\[idx\.description\]\)/);
const publicUser = functionSource('publicUser_');
assert.match(publicUser, /return \{ userId: u\.userId, name: u\.name, phone: u\.phone, email: u\.email, role: u\.role, status: u\.status, photoFileId: u\.photoFileId \|\| '' \}/);
assert.doesNotMatch(publicUser, /passwordHash|passwordSalt|phoneNormalized|emailNormalized/);
const userAdmin = functionSource('getUserManagementData');
assert.match(userAdmin, /requireRole_\(sessionToken, \['SUPERADMIN'\]\)/);
assert.doesNotMatch(userAdmin, /passwordHash|passwordSalt|phoneNormalized|emailNormalized/);
const login = functionSource('login');
assert.match(login, /console\.error\('AUTH_LOGIN_FAILED'\)/);
assert.doesNotMatch(login, /console\.error\(e\)/);
console.log('API response and audit data redaction safeguards passed.');
