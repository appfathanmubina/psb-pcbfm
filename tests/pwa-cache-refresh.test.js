'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('frontend/index.html', 'utf8');
const sw = fs.readFileSync('frontend/sw.js', 'utf8');
const bridge = fs.readFileSync('frontend/api-bridge.js', 'utf8');
const appVersion = html.match(/app\.js\?v=(\d+\.\d+\.\d+)/)?.[1];
const workerVersion = html.match(/sw\.js\?v=(\d+\.\d+\.\d+)/)?.[1];
const workerAssetVersion = sw.match(/\.\/app\.js\?v=(\d+\.\d+\.\d+)/)?.[1];
const workerCacheVersion = sw.match(/const CACHE='psb-pwa-shell-v([\d-]+)'/)?.[1];
assert.ok(workerVersion, 'HTML must request a versioned service worker');
assert.match(sw, new RegExp('PSB PWA ' + workerVersion.replace(/\./g, '\\.') + '\\b'), 'Service worker release marker must match its registration URL');
assert.match(html, /controllerchange/, 'HTML must reload when a new worker takes control');
assert.match(html, /window\.location\.reload\(\)/, 'A newly activated worker must refresh the open PWA');
assert.ok(appVersion, 'Application script must have a versioned URL');
assert.match(html, /styles\.css\?v=32\.37\.0/, 'Stylesheet must have a fresh URL');
assert.equal(workerAssetVersion, appVersion, 'Service worker must precache the same application version requested by HTML');
assert.equal(workerCacheVersion, workerVersion.replace(/\./g, '-'), 'Service worker cache namespace must match the registered release');
assert.match(sw, /new Request\(asset,\{cache:'reload'\}\)/, 'Precache must bypass browser HTTP cache');
assert.match(sw, /CACHE_FIRST_ASSETS\.has\(request\.url\)/, 'Versioned shell assets must render from cache before background refresh');
assert.match(sw, /event\.waitUntil\(update\.catch\(\(\)=>\{\}\)\)/, 'Cached shell assets must refresh in the background');
assert.match(sw, /Dokumen navigasi selalu memeriksa versi terbaru/, 'Navigation documents must remain network-first');
assert.match(sw, /keys\.filter\(key=>key!==CACHE\)/, 'Production worker must clean previous application caches');
assert.match(sw, /self\.clients\.claim\(\)/, 'New worker must control existing tabs');
assert.match(sw, /if\(url\.origin!==self\.location\.origin\)return/, 'Cross-origin Apps Script traffic must stay outside the service worker');
assert.match(html, /api-bridge\.js\?v=32\.19\.0/, 'HTML must request the updated upload bridge');
assert.match(sw, /api-bridge\.js\?v=32\.19\.0/, 'Service worker must precache the updated upload bridge');
assert.match(bridge, /const BRIDGE_URL = "https:\/\/script\.google\.com\/macros\/s\//, 'Apps Script bridge endpoint must remain unchanged');
console.log('PWA desktop cache refresh safeguards: OK');
