'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const html = fs.readFileSync('frontend/index.html', 'utf8');
const sw = fs.readFileSync('frontend/sw.js', 'utf8');
const bridge = fs.readFileSync('frontend/api-bridge.js', 'utf8');
assert.match(html, /sw\.js\?v=32\.15\.0/, 'HTML must request the current service worker');
assert.match(html, /controllerchange/, 'HTML must reload when a new worker takes control');
assert.match(html, /window\.location\.reload\(\)/, 'A newly activated worker must refresh the open PWA');
assert.match(html, /app\.js\?v=32\.15\.0/, 'Application script must have a fresh URL');
assert.match(html, /styles\.css\?v=32\.15\.0/, 'Stylesheet must have a fresh URL');
assert.match(sw, /psb-pwa-shell-v32-14-0/, 'Service worker must use a new cache namespace');
assert.match(sw, /new Request\(asset,\{cache:'reload'\}\)/, 'Precache must bypass browser HTTP cache');
assert.match(sw, /CACHE_FIRST_ASSETS\.has\(request\.url\)/, 'Versioned shell assets must render from cache before background refresh');
assert.match(sw, /event\.waitUntil\(update\.catch\(\(\)=>\{\}\)\)/, 'Cached shell assets must refresh in the background');
assert.match(sw, /Dokumen navigasi selalu memeriksa versi terbaru/, 'Navigation documents must remain network-first');
assert.match(sw, /caches\.delete\(key\)/, 'Activation must remove previous application caches');
assert.match(sw, /self\.clients\.claim\(\)/, 'New worker must control existing tabs');
assert.match(sw, /if\(url\.origin!==self\.location\.origin\)return/, 'Cross-origin Apps Script traffic must stay outside the service worker');
assert.match(bridge, /const BRIDGE_URL = "https:\/\/script\.google\.com\/macros\/s\//, 'Apps Script bridge endpoint must remain unchanged');
console.log('PWA desktop cache refresh safeguards: OK');
